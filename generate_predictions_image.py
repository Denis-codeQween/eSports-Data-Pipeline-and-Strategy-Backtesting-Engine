import os
from datetime import datetime
from PIL import Image, ImageDraw, ImageFont

def clean_emojis(line):
    """ Заменяет тяжелые графические эмодзи на текстовые маркеры, 
        чтобы избежать появления квадратов в шрифте Consolas """
    replacements = {
        "📋 РЕКОМЕНДАЦИИ": "РЕКОМЕНДАЦИИ",  # Убираем ломающийся планшет из заголовков
        "💎 УЛЬТРА": "[УЛЬТРА]",
        "🔥 ВЫСОКИЙ ШАНС": "[ВЫСОКИЙ ШАНС]",
        "❄️ ВЫСОКИЙ ШАНС": "[ВЫСОКИЙ ШАНС]",
        "⚠️ ВНИМАНИЕ": "[ВНИМАНИЕ]",
        "👑 ЖЕЛЕЗНЫЙ ТРЕНД": "[👑 ЖЕЛЕЗНЫЙ ТРЕНД]",
        "📈 ТРЕНД ТУРНИРА": "[ТРЕНД ТУРНИРА]",
        "📉 ТРЕНД ТУРНИРА": "[ТРЕНД ТУРНИРА]",
        "👉 ": " -> ",
        "📊 ": " * ",
        "ℹ️ ": " i "
    }
    for emoji, text in replacements.items():
        line = line.replace(emoji, text)
    return line

def draw_prediction_report(text_report, output_filename="PREDICTIONS_REPORT.png", tournament_name=None):
    # Цветовая палитра
    BG_COLOR = (13, 19, 23)        # Глубокий темный фон
    BORDER_COLOR = (32, 45, 54)    # Серая контурная рамка
    TEXT_COLOR = (240, 244, 248)   # Белый текст контента
    ACCENT_GREEN = (0, 230, 118)   # Зеленый для заголовков и УЛЬТРА
    LIGHT_BLUE = (3, 169, 244)     # Голубой для обычных трендов
    WARN_COLOR = (255, 235, 59)    # Желтый для предупреждений
    FOOTER_COLOR = (120, 144, 156) # Серый подвал

    # Подключение шрифтов
    font_paths = [
        "C:\\Windows\\Fonts\\consola.ttf",
        "C:\\Windows\\Fonts\\lucon.ttf",
        "C:\\Windows\\Fonts\\arial.ttf"
    ]
    font_path = next((p for p in font_paths if os.path.exists(p)), None)
    
    if font_path:
        title_font = ImageFont.truetype(font_path, 26)
        subtitle_font = ImageFont.truetype(font_path, 20)
        body_font = ImageFont.truetype(font_path, 15)
        footer_font = ImageFont.truetype(font_path, 11)
    else:
        title_font = subtitle_font = body_font = footer_font = ImageFont.load_default()

    # Парсим строчки отчета
    raw_lines = text_report.split('\n')
    lines = [line for line in raw_lines if line.strip()]

    # Динамический расчет высоты холста в зависимости от наличия подзаголовка турнира
    line_height = 25
    padding = 50
    footer_height = 50
    
    if tournament_name:
        header_height = 105  # Чуть увеличиваем шапку для названия турнира
        title_y = 35
        tournament_y = 65
        line_y = 90
        start_text_y = 115
    else:
        header_height = 80
        title_y = 45
        line_y = 75
        start_text_y = 100
    
    width = 1050
    height = header_height + (len(lines) * line_height) + padding + footer_height
    if height < 500: height = 500

    img = Image.new("RGB", (width, height), BG_COLOR)
    draw = ImageDraw.Draw(img)

    # Двойная неоновая рамка
    draw.rectangle([15, 15, width - 15, height - 15], outline=BORDER_COLOR, width=2)
    draw.rectangle([20, 20, width - 20, height - 20], outline=BORDER_COLOR, width=1)

    # Главное название
    draw.text((width // 2, title_y), "CS2 АНАЛИТИЧЕСКИЙ СОВЕТНИК V2.0", font=title_font, fill=ACCENT_GREEN, anchor="mm")
    
    # Добавляем название турнира, если оно передано
    if tournament_name:
        draw.text((width // 2, tournament_y), str(tournament_name).upper(), font=body_font, fill=LIGHT_BLUE, anchor="mm")
        
    draw.line([30, line_y, width - 30, line_y], fill=BORDER_COLOR, width=2)

    current_y = start_text_y
    for line in lines:
        if "====" in line or "----" in line:
            continue
            
        cleaned_line = clean_emojis(line)
        
        if "РЕКОМЕНДАЦИИ ПО" in cleaned_line:
            current_y += 10
            draw.text((40, current_y), cleaned_line, font=subtitle_font, fill=ACCENT_GREEN)
            current_y += 30
            continue
        elif "[УЛЬТРА]" in cleaned_line:
            text_fill = ACCENT_GREEN
        elif "[ВНИМАНИЕ]" in cleaned_line:
            text_fill = WARN_COLOR
        elif "[ВЫСОКИЙ ШАНС]" in cleaned_line:
            text_fill = LIGHT_BLUE
        else:
            text_fill = TEXT_COLOR

        draw.text((40, current_y), cleaned_line, font=body_font, fill=text_fill)
        current_y += line_height

    # Подвал с временной меткой
    dt_str = datetime.now().strftime("%d.%m.%Y %H:%M:%S")
    now_str = f"GENERATED BY AI CONSOLE | {dt_str}"
    draw.text((width - 40, height - 35), now_str, font=footer_font, fill=FOOTER_COLOR, anchor="ra")

    img.save(output_filename, "PNG")
    print(f"🖼️  Картинка успешно сохранена: {output_filename}")