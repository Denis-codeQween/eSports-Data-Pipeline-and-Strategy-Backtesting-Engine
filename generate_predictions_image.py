import os
from datetime import datetime
from PIL import Image, ImageDraw, ImageFont

def clean_emojis(line):
    """ Replaces heavy graphic emojis with text markers 
        to prevent square artifacts in the Consolas font """
    replacements = {
        "📋 РЕКОМЕНДАЦИИ": "RECOMMENDATIONS",
        "💎 УЛЬТРА": "[ULTRA]",
        "🔥 ВЫСОКИЙ ШАНС": "[HIGH CHANCE]",
        "❄️ ВЫСОКИЙ ШАНС": "[HIGH CHANCE]",
        "⚠️ ВНИМАНИЕ": "[WARNING]",
        "👑 ЖЕЛЕЗНЫЙ ТРЕНД": "[👑 IRON TREND]",
        "📈 ТРЕНД ТУРНИРА": "[TOURNAMENT TREND]",
        "📉 ТРЕНД ТУРНИРА": "[TOURNAMENT TREND]",
        "👉 ": " -> ",
        "📊 ": " * ",
        "ℹ️ ": " i "
    }
    for emoji, text in replacements.items():
        line = line.replace(emoji, text)
    return line

def draw_prediction_report(text_report, output_filename="PREDICTIONS_REPORT.png", tournament_name=None):
    # Color Palette
    BG_COLOR = (13, 19, 23)        # Deep dark background
    BORDER_COLOR = (32, 45, 54)    # Gray outline border
    TEXT_COLOR = (240, 244, 248)   # White content text
    ACCENT_GREEN = (0, 230, 118)   # Green for titles and ULTRA
    LIGHT_BLUE = (3, 169, 244)     # Blue for standard trends
    WARN_COLOR = (255, 235, 59)    # Yellow for warnings
    FOOTER_COLOR = (120, 144, 156) # Gray footer

    # Font Setup
    font_paths = [
        "C:\\Windows\\Fonts\\consola.ttf",
        "C:\\Windows\\Fonts\\lucon.ttf",
        "C:\\Windows\\Fonts\\arial.ttf"
    ]
    font_path = next((p for p in font_paths if os.path.exists(p)), None)
    
    if font_path:
        title_font = ImageFont.truetype(font_path, 26)
        subtitle_font = ImageFont.truetype(font_path, 20)
        body_font = ImageFont.truetype(font_path, 15)
        footer_font = ImageFont.truetype(font_path, 11)
    else:
        title_font = subtitle_font = body_font = footer_font = ImageFont.load_default()

    # Parse report lines
    raw_lines = text_report.split('\n')
    lines = [line for line in raw_lines if line.strip()]

    # Dynamic canvas height calculation based on tournament subtitle presence
    line_height = 25
    padding = 50
    footer_height = 50
    
    if tournament_name:
        header_height = 105  # Slightly increase header for tournament name
        title_y = 35
        tournament_y = 65
        line_y = 90
        start_text_y = 115
    else:
        header_height = 80
        title_y = 45
        line_y = 75
        start_text_y = 100
    
    width = 1050
    height = header_height + (len(lines) * line_height) + padding + footer_height
    if height < 500: height = 500

    img = Image.new("RGB", (width, height), BG_COLOR)
    draw = ImageDraw.Draw(img)

    # Double neon border
    draw.rectangle([15, 15, width - 15, height - 15], outline=BORDER_COLOR, width=2)
    draw.rectangle([20, 20, width - 20, height - 20], outline=BORDER_COLOR, width=1)

    # Main Title
    draw.text((width // 2, title_y), "CS2 ANALYTICAL ADVISOR V2.0", font=title_font, fill=ACCENT_GREEN, anchor="mm")
    
    # Add tournament name if provided
    if tournament_name:
        draw.text((width // 2, tournament_y), str(tournament_name).upper(), font=body_font, fill=LIGHT_BLUE, anchor="mm")
        
    draw.line([30, line_y, width - 30, line_y], fill=BORDER_COLOR, width=2)

    current_y = start_text_y
    for line in lines:
        if "====" in line or "----" in line:
            continue
            
        cleaned_line = clean_emojis(line)
        
        if "RECOMMENDATIONS" in cleaned_line:
            current_y += 10
            draw.text((40, current_y), cleaned_line, font=subtitle_font, fill=ACCENT_GREEN)
            current_y += 30
            continue
        elif "[ULTRA]" in cleaned_line:
            text_fill = ACCENT_GREEN
        elif "[WARNING]" in cleaned_line:
            text_fill = WARN_COLOR
        elif "[HIGH CHANCE]" in cleaned_line:
            text_fill = LIGHT_BLUE
        else:
            text_fill = TEXT_COLOR

        draw.text((40, current_y), cleaned_line, font=body_font, fill=text_fill)
        current_y += line_height

    # Footer with timestamp
    dt_str = datetime.now().strftime("%d.%m.%Y %H:%M:%S")
    now_str = f"GENERATED BY AI CONSOLE | {dt_str}"
    draw.text((width - 40, height - 35), now_str, font=footer_font, fill=FOOTER_COLOR, anchor="ra")

    img.save(output_filename, "PNG")
    print(f"🖼️ Image successfully saved: {output_filename}")